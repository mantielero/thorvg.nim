# Sanity comparison (NOT a pass criterion): migration\golden_gl (C++ GL engine) vs migration\golden (C++ CPU engine),
# per case and per group, written to migration\GL_SANITY.md.
#   powershell -File tests\gl\gl_sanity.ps1
# Per case: max channel delta, mean abs channel delta over all pixels and 4 channels, % of pixels whose max channel delta > 64.
param([string]$Cases = 'migration\cases.txt', [string]$Out = 'migration\GL_SANITY.md')
[Environment]::CurrentDirectory = (Get-Location).Path
[System.Threading.Thread]::CurrentThread.CurrentCulture = [System.Globalization.CultureInfo]::InvariantCulture
Add-Type -TypeDefinition @'
using System;
using System.IO;
public static class SanityDiff {
  public static void Compare(string a0, string b0, out int maxD, out double meanD, out double pctBig, out long npx) {
    byte[] a = File.ReadAllBytes(a0), b = File.ReadAllBytes(b0);
    maxD = 0; meanD = 0; pctBig = 0; npx = a.Length / 4;
    if (a.Length != b.Length || npx == 0) { maxD = -1; return; }
    long sum = 0, big = 0;
    for (int i = 0; i < a.Length; i += 4) {
      int m = 0;
      for (int k = 0; k < 4; k++) { int d = Math.Abs(a[i + k] - b[i + k]); sum += d; if (d > m) m = d; }
      if (m > maxD) maxD = m;
      if (m > 64) big++;
    }
    meanD = (double)sum / a.Length; pctBig = 100.0 * big / npx;
  }
}
'@
$g = @{}
$rows = @()
foreach ($raw in Get-Content $Cases) {
  $l = $raw.Trim(); if ($l -eq '' -or $l.StartsWith('#')) { continue }
  $name = ($l -split '\|')[0].Trim()
  $grp = ($name -split '_')[0]
  $rg = (Get-Content "migration\golden_gl\$name.rc").Trim(); $rc = (Get-Content "migration\golden\$name.rc").Trim()
  if (-not $g.ContainsKey($grp)) { $g[$grp] = [ordered]@{ n = 0; cmp = 0; skipped = 0; gret = 0; max = 0; maxName = ''; sumMean = 0.0; sumBig = 0.0; ident = 0 } }
  $s = $g[$grp]; $s.n++
  if ($rg -ne '0' -or $rc -ne '0') { $s.skipped++; if ($rg -ne $rc) { $s.gret++ }; continue }
  $md = 0; $mean = 0.0; $big = 0.0; $npx = [long]0
  [SanityDiff]::Compare("migration\golden_gl\$name.argb", "migration\golden\$name.argb", [ref]$md, [ref]$mean, [ref]$big, [ref]$npx)
  if ($md -lt 0) { $s.skipped++; continue }
  $s.cmp++; $s.sumMean += $mean; $s.sumBig += $big
  if ($md -eq 0) { $s.ident++ }
  if ($md -gt $s.max) { $s.max = $md; $s.maxName = $name }
}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# GL_SANITY: C++ GL engine vs C++ CPU engine (sanity only, NOT a pass criterion)')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('golden_gl = `build\cppgl\cpp_gl_driver.exe` (4x MSAA, GPU rasteriser), golden = `build\cpp\cpp_driver.exe` (software rasteriser).')
[void]$sb.AppendLine('Generated by `tests\gl\gl_sanity.ps1`. Premultiplied ARGB dumps compared per channel.')
[void]$sb.AppendLine('mean delta = mean abs channel difference over all pixels and the 4 channels (averaged over the cases of the group);')
[void]$sb.AppendLine('% px > 64 = share of pixels with a channel delta above 64 (averaged over the cases); identical = cases with max delta 0.')
[void]$sb.AppendLine('"skipped" = a driver exited non-zero (case not comparable; `rc differs` = only one of the two failed).')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| group | cases | compared | identical | skipped (rc differs) | max delta | worst case | mean delta | % px > 64 |')
[void]$sb.AppendLine('|---|---|---|---|---|---|---|---|---|')
foreach ($k in ($g.Keys | Sort-Object)) {
  $s = $g[$k]
  $mm = if ($s.cmp -gt 0) { '{0:N4}' -f ($s.sumMean / $s.cmp) } else { '-' }
  $bb = if ($s.cmp -gt 0) { '{0:N3}' -f ($s.sumBig / $s.cmp) } else { '-' }
  [void]$sb.AppendLine("| $k | $($s.n) | $($s.cmp) | $($s.ident) | $($s.skipped) ($($s.gret)) | $($s.max) | $($s.maxName) | $mm | $bb |")
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Reading: GL differs from the CPU rasteriser at edges (4x MSAA quantises coverage to 0x40/0x80/0xBF/0xFF) and in')
[void]$sb.AppendLine('texture sampling of scaled/rotated images (bilinear in the shader vs the CPU scanline sampler), so the CPU golden can never be')
[void]$sb.AppendLine('the pass criterion of the GL port; only `migration\golden_gl` (original C++ GL engine) is. Unscaled images at native size')
[void]$sb.AppendLine('(png/jpg/webp 1:1) are mostly identical (png native <= 2 levels in the earlier smoke measurement).')
Set-Content -Encoding UTF8 $Out $sb.ToString()
Write-Host (Get-Content $Out -Raw)
