# Regenerates migration\cases.txt (run from the project root).  Format: name | <driver arguments>
# Paths in the arguments are relative to the project root (all parity scripts run from there).
$cases = New-Object System.Collections.Generic.List[string]
$cases.Add('# ThorVG parity cases: name | scene width height   (see tests\parity\README.md)')
$cases.Add('# --- vector shapes (design canvas 400x300) ---')
$cases.Add('shapes_all | shapes 400 300')
$cases.Add('shapes_all_odd | shapes 333 211')
foreach ($p in 'rect','roundrect','ellipse','star_nonzero','star_evenodd','lingrad','radgrad','spread_reflect','spread_repeat','gradstroke','caps','joins','dash','transform','opacity','clip','mask','blend','nested') {
  $cases.Add("shapes_$p | shapes:$p 400 300")
}
$cases.Add('# --- SVG (hand written) ---')
foreach ($f in 'shapes_basic','gradient','path_arcs','transform','clippath','dash','style_use') {
  $cases.Add("svg_$f | svg:tests/data/$f.svg 480 320")
}
$cases.Add('svg_shapes_basic_small | svg:tests/data/shapes_basic.svg 100 75')
$cases.Add('svg_gradient_native | svg:tests/data/gradient.svg 240 160')
$cases.Add('# --- SVG (copied from upstream test/res) ---')
foreach ($i in 0..5) { $cases.Add("svg_upstream_test$i | svg:tests/data/upstream/test$i.svg 500 500") }
$cases.Add('# --- PNG (generated by tests\parity\mkpng.js; native size = direct blit, 128x128 = scaled) ---')
foreach ($f in Get-ChildItem tests\data\png\*.png | Sort-Object Name) {
  $n = $f.BaseName
  $cases.Add("png_${n}_native | png:tests/data/png/$n.png " + $(if ($n -eq 'rgba8_big') { '200 150' } elseif ($n -eq 'rgb8_adam7') { '5 3' } else { '37 29' }))
}
foreach ($n in 'rgba8','pal4','gray2','rgb16','rgba8_adam7','rgb8_adam7') { $cases.Add("png_${n}_scaled | png:tests/data/png/$n.png 128 128") }
$cases.Add('png_upstream_test_native | png:tests/data/upstream/test.png 511 511')
$cases.Add('png_upstream_test_down | png:tests/data/upstream/test.png 256 200')
$cases.Add('png_upstream_test2_up | png:tests/data/upstream/test2.png 30 20')
$cases.Add('# --- text ---')
$cases.Add('text_arial | text 400 300')
$cases.Add('text_arial_big | text 800 600')
$cases.Add('text_publicsans | text:tests/data/upstream/PublicSans-Regular.ttf 400 300')
$cases.Add('# --- PNG mapped through rotation/shear/scale (texmap path); scene pngrot:<file>@deg,scale,shear,opacity ---')
$cases.Add('pngrot_rgba8_r30 | pngrot:tests/data/png/rgba8.png@30,1,0,255 64 64')
$cases.Add('pngrot_rgba8_r90 | pngrot:tests/data/png/rgba8.png@90,1,0,255 48 48')
$cases.Add('pngrot_rgba8_r180 | pngrot:tests/data/png/rgba8.png@180,1,0,255 48 48')
$cases.Add('pngrot_rgba8_r45_x2 | pngrot:tests/data/png/rgba8.png@45,2,0,255 120 120')
$cases.Add('pngrot_rgb8_r20_half | pngrot:tests/data/png/rgb8.png@-20,0.5,0,255 40 40')
$cases.Add('pngrot_rgba8_shear | pngrot:tests/data/png/rgba8.png@0,1.5,0.5,255 100 80')
$cases.Add('pngrot_pal4_r135_op | pngrot:tests/data/png/pal4.png@135,2,0,128 100 100')
$cases.Add('pngrot_graya8_r10_shear | pngrot:tests/data/png/graya8.png@10,2,-0.3,255 100 100')
$cases.Add('pngrot_rgba16_clip | pngrot:tests/data/png/rgba16.png@30,3,0,255 60 60')
$cases.Add('pngrot_big_r25 | pngrot:tests/data/png/rgba8_big.png@25,1,0,255 300 300')
$cases.Add('pngrot_upstream_test_r25 | pngrot:tests/data/upstream/test.png@25,0.5,0,255 400 400')
$cases.Add('pngrot_upstream_test2_r17_up | pngrot:tests/data/upstream/test2.png@17,10,0,255 64 64')
$cases.Add('pngrot_rgb8_adam7_r60_op | pngrot:tests/data/png/rgb8_adam7.png@60,8,0,200 64 64')
$cases.Add('pngrot_gray1_rm90 | pngrot:tests/data/png/gray1.png@-90,1,0,255 50 50')
$cases.Add('pngrot_rgba8_r30_edge | pngrot:tests/data/png/rgba8.png@30,1.5,0,255 30 30')
[IO.File]::WriteAllLines("$PWD\migration\cases.txt", $cases)
"wrote $($cases.Count) lines"
