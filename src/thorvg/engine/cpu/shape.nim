## Shape outlines: fill and stroke scan conversion of a `RenderShape`.
##
## Ported from `src/renderer/cpu_engine/tvgSwShape.cpp` (the dash code lives in
## `dash.nim`, the fixed-point export in `util.nim`). The C++ outline points at the
## shape's path; here it holds a copy of the commands and the float points (`fpts`),
## and `utilExport` derives the fixed-point `pts` that `rleRender` reads.
## The memory pool, `tid` and `rleFree`/`strokeFree` parameters are gone (GC).

import std/options
import ../../core/[types, geom, path]
import ../../renderer/[render, trim]
import ./[common, rle, stroke, util, dash]

export dash.DashPatternThreshold

proc genOutline(rshape: RenderShape, trimmed: bool): SwOutline =
  ## Outline of the (optionally trimmed) path; nil if empty or starting with a cubic.
  var src: RenderPath
  if trimmed:
    if rshape.stroke.isNone or not rshape.stroke.get.trim.trim(rshape.path, src):
      return nil
  else:
    src = rshape.path
  if src.empty or src.cmds.len == 0 or src.cmds[0] == PathCommand.CubicTo: return nil
  SwOutline(cmds: src.cmds, fpts: src.pts, fillRule: rshape.rule)

func axisAlignedRect(outline: SwOutline): bool =
  # TODO (C++): return false if the coordinates have a fractional part
  let cmds {.cursor.} = outline.cmds
  if cmds.len != 5 or (cmds[0] != PathCommand.MoveTo and cmds[0] != PathCommand.LineTo):
    return false
  for i in 1 ..< 4:
    if cmds[i] != PathCommand.LineTo: return false
  if cmds[4] != PathCommand.Close and cmds[4] != PathCommand.LineTo: return false

  let pt1 = outline.pts[0]
  let pt2 = outline.pts[1]
  let pt3 = outline.pts[2]
  let pt4 = outline.pts[3]
  let a = SwPoint(x: pt1.x, y: pt3.y)
  let b = SwPoint(x: pt3.x, y: pt1.y)
  func same(p, q: SwPoint): bool = p.x == q.x and p.y == q.y
  (same(pt2, a) and same(pt4, b)) or (same(pt2, b) and same(pt4, a))

proc shapeGenRle*(shape: SwShape, rshape: RenderShape, transform: Matrix, clipBox: Region,
                  renderBox: var Region, composite, antiAlias: bool): bool =
  ## Builds the fill outline and rle of `shape`; `renderBox` receives the clipped bounds.
  let outline = genOutline(rshape, rshape.trimpath)
  if outline == nil:
    renderBox = Region()
    return false

  var bbox: BBox
  utilExport(outline, transform, bbox)

  shape.outline = outline
  # an axis-aligned rectangle needs no rle (unless it is composited)
  shape.fastTrack = not composite and axisAlignedRect(outline)

  if not utilBBox(bbox, clipBox, renderBox, shape.fastTrack): return false
  shape.bbox = renderBox

  if shape.fastTrack: return true

  shape.rle = rleRender(shape.rle, outline, renderBox, antiAlias)
  shape.rle != nil

proc shapeDelOutline*(shape: SwShape) =
  shape.outline = nil

proc shapeReset*(shape: SwShape) =
  rleReset(shape.rle)
  shape.outline = nil
  shape.bbox = Region()
  shape.fastTrack = false

proc shapeDelStroke*(shape: SwShape) =
  if shape.stroke == nil: return
  shape.strokeRle = nil
  shape.stroke = nil

proc shapeFree*(shape: SwShape) =
  shape.rle = nil
  shape.fill = nil
  shapeDelStroke(shape)

proc shapeResetStroke*(shape: SwShape, rshape: RenderShape, transform: Matrix) =
  if shape.stroke == nil: shape.stroke = SwStroke()
  strokeReset(shape.stroke, rshape, transform)
  rleReset(shape.strokeRle)

proc shapeGenStrokeRle*(shape: SwShape, rshape: RenderShape, transform: Matrix,
                        clipBox: Region, renderBox: var Region, antiAlias: bool): bool =
  ## Strokes the (dashed, trimmed) path of `rshape` into `shape.strokeRle`.
  if rshape.stroke.isNone: return false
  shapeResetStroke(shape, rshape, transform)

  let dashed = rshape.stroke.get.dash.length > DashPatternThreshold
  var outline: SwOutline
  if dashed:
    outline = genDashOutline(rshape, rshape.trimpath)
  elif shape.outline != nil:
    outline = shape.outline          # reuse the outline generated by the fill
  else:
    outline = genOutline(rshape, rshape.trimpath)
  if outline == nil: return false

  if not strokeParseOutline(shape.stroke, outline): return false
  outline = strokeExportOutline(shape.stroke)
  if outline.fpts.len == 0: return false
  var bbox: BBox
  utilExport(outline, transform, bbox)
  if not utilBBox(bbox, clipBox, renderBox, false): return false

  shape.strokeRle = rleRender(shape.strokeRle, outline, renderBox, antiAlias)
  shape.strokeRle != nil

proc shapeStrokeBBox*(shape: SwShape, rshape: RenderShape, pt4: var array[4, Point],
                      m: Matrix): bool =
  ## Bounds of the stroke borders transformed by `m` (corners clockwise from min).
  if rshape.strokeWidth <= 0.0'f32: return false
  let outline = genOutline(rshape, rshape.trimpath)
  if outline == nil: return false

  if shape.stroke == nil: shape.stroke = SwStroke()
  strokeReset(shape.stroke, rshape, m)
  discard strokeParseOutline(shape.stroke, outline)

  var bounds = initBBox()
  for border in shape.stroke.borders:
    for pt in border.pts:
      let t = pt * m
      if t.x < bounds.min.x: bounds.min.x = t.x
      if t.x > bounds.max.x: bounds.max.x = t.x
      if t.y < bounds.min.y: bounds.min.y = t.y
      if t.y > bounds.max.y: bounds.max.y = t.y

  pt4[0] = bounds.min
  pt4[1] = Point(x: bounds.max.x, y: bounds.min.y)
  pt4[2] = bounds.max
  pt4[3] = Point(x: bounds.min.x, y: bounds.max.y)
  true
